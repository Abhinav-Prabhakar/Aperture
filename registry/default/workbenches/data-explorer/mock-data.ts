const POINTS = 9;

function buildSeries(seed: Seed, index: number): readonly number[] {
  const reference = seed.concentration ?? seed.a600 * 20;
  const [startFactor, endFactor] = seed.curve;
  return Array.from({ length: POINTS }, (_, point) => {
    const progress = point / (POINTS - 1);
    const base =
      reference * (startFactor + (endFactor - startFactor) * progress);
    const wiggle = Math.sin((index + 1) * (point + 1)) * 0.08;
    return Number(Math.max(0, base + wiggle).toFixed(2));
  });
}

export const MOCK_SAMPLES: readonly ExplorerSample[] = SEED.map(
  (seed, index) => ({
    ...seed,
    series: buildSeries(seed, index),
  }),
);
