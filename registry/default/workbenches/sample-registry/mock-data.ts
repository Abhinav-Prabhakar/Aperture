import type { Aliquot, RegistrySample, StorageLocation } from "./types";

export const MOCK_AS_OF = "2026-11-22T09:00:00Z";

function aliquots(
  sampleId: string,
  location: StorageLocation,
  volumes: readonly (number | null)[],
  status: Aliquot["status"] = "stored",
): Aliquot[] {
  return volumes.map((volumeUl, index) => ({
    id: `${sampleId}-A${index + 1}`,
    volumeUl,
    location: `${location.box} · ${String(index + 1).padStart(2, "0")}`,
    status,
  }));
}

